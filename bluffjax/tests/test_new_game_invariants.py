class TestKempsInvariants:
    """
    Ground truth from kemps.py:
    - KempsState.agent_hands: (num_agents, hand_size) card *indices* (0..deck_size-1)
    - KempsState.center_cards: (4,) card indices
    - KempsState.deck: remaining, undealt card indices, consumed via deck_idx
    - Every card index should appear in EXACTLY ONE of
      {agent_hands, center_cards, deck[deck_idx:]} at all times -- this is a
      much stronger check than a count-conservation check, because it also
      catches the swap logic (_process_swaps) accidentally duplicating or
      losing a specific card, which a pure count-based check could miss if a
      duplicate-for-duplicate swap happened to still sum correctly.
    - agent_hand_counts / center_counts (rank histograms) must always match
      the ranks implied by the actual card indices in agent_hands / center_cards.
    """

    def _env(self, num_agents=4):
        return make("kemps", num_agents=num_agents, horizon=ROLLOUT_LEN)

    def _check_no_duplicate_or_missing_cards(self, env, state, t):
        all_cards = jnp.concatenate(
            [
                state.agent_hands.reshape(-1),
                state.center_cards.reshape(-1),
                state.deck[state.deck_idx :],
            ]
        )
        deck_size = env.deck_size
        counts = jnp.bincount(all_cards, length=deck_size)
        assert jnp.all(counts == 1), (
            f"Card-uniqueness invariant violated at step {t}: "
            f"{int((counts == 0).sum())} cards missing, "
            f"{int((counts > 1).sum())} cards duplicated. "
            f"Expected every card index in [0,{deck_size}) to appear exactly once "
            f"across agent_hands + center_cards + remaining deck."
        )

    def _check_rank_counts_consistent(self, env, state, t):
        def ranks_of(cards):
            return cards // env.num_suits

        for agent in range(env.num_agents):
            recomputed = jnp.bincount(
                ranks_of(state.agent_hands[agent]),
                length=env.num_ranks,
                minlength=env.num_ranks,
            )
            assert jnp.array_equal(state.agent_hand_counts[agent], recomputed), (
                f"agent_hand_counts[{agent}] drifted from actual hand at step {t}"
            )
        recomputed_center = jnp.bincount(
            ranks_of(state.center_cards), length=env.num_ranks, minlength=env.num_ranks
        )
        assert jnp.array_equal(state.center_counts, recomputed_center), (
            f"center_counts drifted from actual center cards at step {t}"
        )

    def test_card_uniqueness_and_rank_counts(self):
        env = self._env(num_agents=4)
        rng = jax.random.PRNGKey(SEED)
        for i in range(N_RANDOM_ROLLOUTS):
            rng, reset_rng = jax.random.split(rng)
            state, obs = env.reset(reset_rng)
            for t in range(ROLLOUT_LEN):
                self._check_no_duplicate_or_missing_cards(env, state, t)
                self._check_rank_counts_consistent(env, state, t)
                if bool(state.done):
                    break
                avail = env.get_avail_actions(state)
                assert avail.all(axis=1).any() or avail.any(axis=1).all(), (
                    "Every agent should have >=1 legal action every step "
                    "(Kemps is simultaneous-move; noop is always legal)"
                )
                rng, act_rng, step_rng = jax.random.split(rng, 3)
                actions = jnp.stack(
                    [
                        _random_action(k, avail[a])
                        for a, k in enumerate(jax.random.split(act_rng, env.num_agents))
                    ]
                )
                state, obs, reward, absorbing, done, info = env.step(
                    step_rng, state, actions
                )

    def test_declare_rewards_are_zero_sum(self):
        """When a KEMPS/STOP KEMPS declaration resolves, reward is +/-1 per
        agent based on team membership (resolve_kemps / resolve_stop in
        kemps.py) -- by construction this should sum to exactly 0 across all
        4 agents every time a declaration fires. This is the single check
        that most directly demonstrates the game is well-posed as a
        zero-sum benchmark, addressing the AC's concern that correctness
        claims for the new games rest on self-consistency alone -- at least
        make that self-consistency check explicit and automated."""
        env = self._env(num_agents=4)
        rng = jax.random.PRNGKey(SEED)
        declare_events_checked = 0
        for i in range(N_RANDOM_ROLLOUTS):
            rng, reset_rng = jax.random.split(rng)
            state, obs = env.reset(reset_rng)
            for t in range(ROLLOUT_LEN):
                if bool(state.done):
                    break
                avail = env.get_avail_actions(state)
                rng, act_rng, step_rng = jax.random.split(rng, 3)
                # Bias toward declaring occasionally so this invariant actually
                # gets exercised rather than only ever hitting noop/swap.
                actions = jnp.stack(
                    [
                        _random_action(k, avail[a])
                        for a, k in enumerate(jax.random.split(act_rng, env.num_agents))
                    ]
                )
                state, obs, reward, absorbing, done, info = env.step(
                    step_rng, state, actions
                )
                if bool(done) and float(jnp.abs(reward).sum()) > 0:
                    assert jnp.isclose(reward.sum(), 0.0), (
                        f"Declaration reward not zero-sum: {reward} at step {t}"
                    )
                    declare_events_checked += 1
        assert declare_events_checked > 0, (
            "No KEMPS/STOP_KEMPS declarations were ever sampled under pure "
            "random play across all rollouts -- increase N_RANDOM_ROLLOUTS/"
            "ROLLOUT_LEN or bias the random policy toward declare actions, "
            "otherwise this test isn't actually exercising the invariant."
        )
