import jax
import jax.numpy as jnp
import pytest

from bluffjax import make


N_RANDOM_ROLLOUTS = 200
ROLLOUT_LEN = 150
SEED = 0


def _random_action(rng, avail):
    """Sample uniformly from legal actions given a boolean avail-action mask."""
    logits = jnp.where(avail, 0.0, -1e9)
    return jax.random.categorical(rng, logits)


