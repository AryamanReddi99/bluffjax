class TestBluffInvariants:
    """
    Ground truth for these invariants comes directly from bluff.py:
    - BluffState.agent_hands: (num_agents, num_ranks) float counts per rank
    - BluffState.pile_hand: (num_ranks,) float counts per rank, cards in the
      central discard pile
    - reset() deals: agent_hands.sum() + pile_hand.sum() == deck_size always,
      since every card starts in exactly one of {a player's hand, the pile}
      and cards only ever move between agent_hands and pile_hand (do_play adds
      to pile_hand / removes from agent_hands; resolve_challenge adds pile
      back into the loser's hand and empties the pile). No card is ever
      created or destroyed by step_env.
    - agent_hand_sizes is maintained as agent_hands.sum(axis=1) at every
      state transition (see finish_play, resolve_challenge) -- should always
      be consistent, not just an independently-tracked counter that could
      drift from the real hand contents.
    """

    def _env(self, num_agents=3):
        return make("bluff", num_agents=num_agents, horizon=ROLLOUT_LEN)

    def _rollout(self, env, rng, max_steps=ROLLOUT_LEN):
        """Random-legal-action rollout, checking invariants at every step."""
        rng, reset_rng = jax.random.split(rng)
        state, obs = env.reset(reset_rng)
        deck_size = env.deck_size

        for t in range(max_steps):
            # --- invariant 1: card conservation ---
            total_cards = state.agent_hands.sum() + state.pile_hand.sum()
            assert jnp.isclose(total_cards, deck_size), (
                f"Card conservation violated at step {t}: "
                f"agent_hands.sum()={state.agent_hands.sum()} + "
                f"pile_hand.sum()={state.pile_hand.sum()} != deck_size={deck_size}"
            )

            # --- invariant 2: hand-size counter matches actual hand contents ---
            recomputed_sizes = state.agent_hands.sum(axis=1).astype(jnp.int32)
            assert jnp.array_equal(state.agent_hand_sizes, recomputed_sizes), (
                f"agent_hand_sizes drifted from agent_hands at step {t}: "
                f"tracked={state.agent_hand_sizes} recomputed={recomputed_sizes}"
            )

            # --- invariant 3: no negative card counts anywhere ---
            assert (state.agent_hands >= 0).all(), f"Negative hand count at step {t}"
            assert (state.pile_hand >= 0).all(), f"Negative pile count at step {t}"

            if bool(state.done):
                break

            # --- invariant 4: acting player always has >=1 legal action ---
            avail = env.get_avail_actions(state)
            assert avail.any(), (
                f"No legal actions available for the acting player at step {t}, "
                f"phase={state.phase} -- possible deadlock in game logic"
            )

            rng, act_rng, step_rng = jax.random.split(rng, 3)
            action = _random_action(act_rng, avail)
            state, obs, reward, absorbing, done, info = env.step(step_rng, state, action)

        return state

    def test_card_conservation_and_hand_size_consistency(self):
        env = self._env(num_agents=3)
        rng = jax.random.PRNGKey(SEED)
        for i in range(N_RANDOM_ROLLOUTS):
            rng, sub = jax.random.split(rng)
            self._rollout(env, sub)

    @pytest.mark.parametrize("num_agents", [2, 3, 4, 5])
    def test_card_conservation_various_player_counts(self, num_agents):
        env = self._env(num_agents=num_agents)
        rng = jax.random.PRNGKey(SEED + num_agents)
        for i in range(20):
            rng, sub = jax.random.split(rng)
            self._rollout(env, sub)

    def test_claim_size_never_exceeds_hand_or_cap(self):
        """Claimed size must be in [1,4] and the claimant must have had at
        least that many cards in hand at the moment of claiming (phase 0 ->
        1 transition). Checked via the claim_size field set in do_claim,
        which is min(action,3)+1, bounded correctly by construction in code
        -- this test exists to catch a *regression* if that logic changes."""
        env = self._env(num_agents=3)
        rng = jax.random.PRNGKey(SEED)
        rng, reset_rng = jax.random.split(rng)
        state, obs = env.reset(reset_rng)
        for t in range(ROLLOUT_LEN):
            if bool(state.done):
                break
            if int(state.phase) == 0:  # about to claim
                hand_size_before = int(
                    state.agent_hand_sizes[state.current_player_idx]
                )
            avail = env.get_avail_actions(state)
            assert avail.any()
            rng, act_rng, step_rng = jax.random.split(rng, 3)
            action = _random_action(act_rng, avail)
            state, obs, reward, absorbing, done, info = env.step(step_rng, state, action)
            if int(state.phase) == 1 and "claim_size" in info:
                assert 1 <= int(state.claim_size) <= 4
                assert int(state.claim_size) <= max(1, hand_size_before)


